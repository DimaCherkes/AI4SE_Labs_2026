#!/usr/bin/env python3
"""
Evaluate and compare all predictions generated by different prompting frameworks.
"""
import csv
import json
from collections import defaultdict, deque
from pathlib import Path
import evaluate_retrieval_predictions as eval_script

DATA_DIR = Path(__file__).resolve().parent

FRAMEWORKS = [
    ("CO-STAR", "restaurants_dataset_predictions_costar.csv", "metadata_costar.json"),
    ("ICIO", "restaurants_dataset_predictions_icio.csv", "metadata_icio.json"),
    ("Few-Shot", "restaurants_dataset_predictions_fewshot.csv", "metadata_fewshot.json"),
]

def main():
    csv.field_size_limit(1_000_000_000)
    conn = eval_script.load_database()
    
    print(f"{'Framework':<12} | {'Correct':<9} | {'Accuracy':<10} | {'Syntax Err':<10} | {'Total Time (s)':<15} | {'Avg Latency (ms)':<16}")
    print("-" * 85)
    
    results = []
    for name, pred_file, meta_file in FRAMEWORKS:
        labels = defaultdict(deque)
        with eval_script.LABELS_PATH.open(encoding="utf-8", newline="") as src:
            for r in csv.DictReader(src):
                labels[r["question"]].append(json.loads(r["result"]))
                
        pred_path = DATA_DIR / pred_file
        meta_path = DATA_DIR / meta_file
        
        metadata = {}
        if meta_path.exists():
            with meta_path.open(encoding="utf-8") as mf:
                metadata = json.load(mf)
                
        total, correct, syntax_errors = 0, 0, 0
        with pred_path.open(encoding="utf-8", newline="") as src:
            for r in csv.DictReader(src):
                q = r["question"]
                sql = r["predicted_sql"]
                exp = labels[q].popleft()
                total += 1
                try:
                    rows = conn.execute(sql).fetchall()
                    if eval_script.row_multiset(rows) == eval_script.row_multiset(exp):
                        correct += 1
                except Exception:
                    syntax_errors += 1
                    
        acc = correct / total if total > 0 else 0.0
        tot_time = metadata.get("total_inference_time_seconds", 0.0)
        avg_lat = metadata.get("avg_latency_ms", 0.0)
        
        print(f"{name:<12} | {correct}/{total:<7} | {acc:>8.2%} | {syntax_errors:<10} | {tot_time:>14.2f} | {avg_lat:>16.2f}")
        results.append({
            "name": name,
            "correct": correct,
            "total": total,
            "accuracy": acc,
            "syntax_errors": syntax_errors,
            "total_time_s": tot_time,
            "avg_latency_ms": avg_lat,
        })
        
    conn.close()
    return results

if __name__ == "__main__":
    main()
